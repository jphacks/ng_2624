import { createHttpServer } from './http.ts';
import { createRequire } from 'node:module';
import { createApp } from './app.ts';
import { createDB, readConfig } from './core.ts';
import { prepareProduct, fetchResolvedProductImage } from './preview.ts';
import { createReply, createGeminiGenerator, searchRetail } from '../ai/index.ts';
const require = createRequire(import.meta.url);
const QRCode = require('qrcode') as { toDataURL: (url: string, options: object) => Promise<string> };
const config = readConfig();
const app = createApp(config, { db: createDB(config), ai: input => createReply(input, { generate: createGeminiGenerator({ apiKey: config.geminiKey }), search: searchRetail }), enrich: prepareProduct, image: fetchResolvedProductImage, qr: url => QRCode.toDataURL(url, { width: 260, margin: 2, errorCorrectionLevel: 'M' }) });
const server = createHttpServer(config, app);
server.listen(config.port, process.env.HOST || '127.0.0.1', () => console.log(`ふぁみぽぽ: ${config.origin}`));
